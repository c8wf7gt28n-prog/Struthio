"""Sprite asset conversion: `.sprite` text grids -> generated C header.

Format (version 0.2):
    # comments start with '#'
    size <w> <h>
    <h rows of exactly w characters: '.' = transparent (0), 0-9 a-f = palette index>
"""

import re

MAX_W = MAX_H = 64
_PIXEL = {c: i for i, c in enumerate("0123456789abcdef")}
_PIXEL["."] = 0


class AssetError(ValueError):
    pass


def parse_sprite(text, name="sprite"):
    rows, size = [], None
    for lineno, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].rstrip()
        if not line:
            continue
        if size is None:
            m = re.fullmatch(r"size\s+(\d+)\s+(\d+)", line.strip())
            if not m:
                raise AssetError("%s:%d: expected 'size <w> <h>'" % (name, lineno))
            size = (int(m.group(1)), int(m.group(2)))
            if not (1 <= size[0] <= MAX_W and 1 <= size[1] <= MAX_H):
                raise AssetError("%s:%d: size must be 1..%d x 1..%d" % (name, lineno, MAX_W, MAX_H))
            continue
        if len(line) != size[0]:
            raise AssetError("%s:%d: row has %d pixels, expected %d" % (name, lineno, len(line), size[0]))
        try:
            rows.append([_PIXEL[c] for c in line.lower()])
        except KeyError as e:
            raise AssetError("%s:%d: invalid pixel character %s" % (name, lineno, e))
    if size is None:
        raise AssetError("%s: missing 'size' line" % name)
    if len(rows) != size[1]:
        raise AssetError("%s: %d rows, expected %d" % (name, len(rows), size[1]))
    return size[0], size[1], [p for r in rows for p in r]


def header_for(sprites):
    """sprites: list of (symbol, w, h, pixels, source_path, sha256)."""
    out = ["/* GENERATED by `arc1 build` from assets/. Do not edit. */",
           "#ifndef ARC1_ASSETS_H", "#define ARC1_ASSETS_H", "", "#include <stdint.h>", ""]
    for sym, w, h, px, src, digest in sprites:
        out.append("/* %s sha256:%s */" % (src, digest))
        out.append("#define ARC1_ASSET_%s_W %d" % (sym, w))
        out.append("#define ARC1_ASSET_%s_H %d" % (sym, h))
        out.append("static const uint8_t ARC1_ASSET_%s[%d] = {" % (sym, w * h))
        for y in range(h):
            out.append("    " + ", ".join(str(p) for p in px[y * w:(y + 1) * w]) + ",")
        out.append("};")
        out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"
