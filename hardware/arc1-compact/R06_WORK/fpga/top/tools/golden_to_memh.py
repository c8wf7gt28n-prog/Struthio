#!/usr/bin/env python3
"""Turn selected R05 protocol golden frames into $readmemh files for tb_top.

Usage: golden_to_memh.py R05_BASELINE/protocol/reference/golden_vectors.json OUTDIR
Writes OUTDIR/golden_<i>.memh and OUTDIR/golden_frames.svh. The frames are
copied byte-for-byte; tb_top checks that the mailbox returns them unchanged.
"""
import json
import os
import sys

NAMES = ["hello_epoch_one", "job_one_byte", "job_endian_probe", "job_max_payload", "result_max_payload"]


def main(src, out):
    os.makedirs(out, exist_ok=True)
    vec = {v["name"]: v for v in json.load(open(src, encoding="utf-8"))["vectors"]}
    lens = []
    for i, n in enumerate(NAMES):
        b = bytes.fromhex(vec[n]["frame_hex"])
        lens.append(len(b))
        with open(os.path.join(out, f"golden_{i}.memh"), "w") as f:
            f.write("\n".join(f"{x:02x}" for x in b) + "\n")
    with open(os.path.join(out, "golden_frames.svh"), "w") as f:
        f.write(f"// generated by golden_to_memh.py from {os.path.basename(src)}\n")
        f.write(f"localparam integer NGOLD = {len(NAMES)};\n")
        f.write("function integer golden_len(input integer i);\n  case (i)\n")
        for i, (n, l) in enumerate(zip(NAMES, lens)):
            f.write(f"    {i}: golden_len = {l}; // {n}\n")
        f.write("    default: golden_len = 0;\n  endcase\nendfunction\n")
    print(f"wrote {len(NAMES)} golden frames: {lens}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(2)
    main(sys.argv[1], sys.argv[2])
