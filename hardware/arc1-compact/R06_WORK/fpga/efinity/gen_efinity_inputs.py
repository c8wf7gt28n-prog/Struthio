#!/usr/bin/env python3
"""Generate Efinity inputs for the R06 T35 top level from the board plan.

Usage: gen_efinity_inputs.py [OUTDIR]   (default: this directory)
Outputs:
  arc1_t35_r06_pins.csv      top-level port -> ball/bank/direction/IO standard
  arc1_t35_r06_isf.py        Interface Designer script (UNVALIDATED: never run,
                             Efinity is not installed in the R06 environment)
Labels: SELECTED_UNVERIFIED pin data; NATIVE_EDA_NOT_RUN.
"""
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PLAN = os.path.join(HERE, "..", "..", "board", "r06_board_plan.json")

# board net -> (top-level port base, Interface Designer GPIO mode)
PORTS = {
    "PSRAM_CE_N": ("psram_ce_n", "output"),
    "PSRAM_SCLK": ("psram_sclk", "output"),
    "PSRAM_SIO0": ("psram_sio[0]", "inout"),
    "PSRAM_SIO1": ("psram_sio[1]", "inout"),
    "PSRAM_SIO2": ("psram_sio[2]", "inout"),
    "PSRAM_SIO3": ("psram_sio[3]", "inout"),
    "T35_SCK":    ("t35_sck", "input"),
    "T35_SS_N":   ("t35_ss_n", "input"),
    "T35_MOSI":   ("t35_mosi", "input"),
    "T35_MISO":   ("t35_miso", "output_oe"),
    "T35_IRQ_N":  ("t35_irq_n", "output_oe"),
    "T35_OSC_25M": ("osc_25m", "clkin"),
    "T35_LED0":   ("t35_led0", "output"),
    "T35_DBG_TX": ("t35_dbg_tx", "output"),
}


def main(out):
    plan = json.load(open(PLAN, encoding="utf-8"))
    rows = []
    for ball, p in sorted(plan["t35"]["pins"].items(), key=lambda kv: kv[1]["net"]):
        if p["net"] not in PORTS:
            continue
        port, mode = PORTS[p["net"]]
        rail = plan["t35"]["bank_rails"][p["bank"]]
        std = {"3V3": "3.3_V_LVTTL_/_LVCMOS"}.get(rail, f"UNSUPPORTED_{rail}")
        pull = "weak pull-up" if p["net"] in ("T35_SS_N",) else "none"
        rows.append({"port": port, "mode": mode, "ball": ball, "pin_name": p["name"], "bank": p["bank"],
                     "io_standard": std, "pull": pull, "net": p["net"]})
    with open(os.path.join(out, "arc1_t35_r06_pins.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    lines = [
        "# GENERATED by gen_efinity_inputs.py -- UNVALIDATED.",
        "# Efinity Interface Designer Python API script for T35F400C3 (R06 draft).",
        "# It has NEVER been executed: Efinity is not installed in the environment that",
        "# produced it. Check every call against the API reference shipped with your",
        "# Efinity version (Interface Designer > Python API) before relying on it.",
        "import os, sys",
        "sys.path.append(os.path.join(os.environ['EFINITY_HOME'], 'pt', 'bin'))",
        "from api_service.design import DesignAPI  # noqa: E402",
        "",
        "design = DesignAPI(False)",
        "design.create('arc1_t35_r06', 'T35F400C3', os.path.dirname(os.path.abspath(__file__)))",
    ]
    for r in rows:
        name = r["port"].replace("[", "_").replace("]", "")
        if r["mode"] == "input":
            lines.append(f"design.create_input_gpio('{name}')")
            lines.append(f"design.set_property('{name}', 'IN_PIN', '{r['port'].split('[')[0]}_IN')")
        elif r["mode"] == "clkin":
            lines.append(f"design.create_input_clock_gpio('{name}')")
        elif r["mode"] == "output":
            lines.append(f"design.create_output_gpio('{name}')")
        else:
            lines.append(f"design.create_inout_gpio('{name}')")
        lines.append(f"design.assign_pkg_pin('{name}', '{r['ball']}')  # {r['pin_name']} {r['bank']} {r['net']}")
    lines += [
        "# PLL: osc_25m -> sys_clk 80 MHz, psram_mclk 40 MHz, pll_locked (create in the GUI or with",
        "# the PLL API of your Efinity version; frequencies are SELECTED, not timing-closed).",
        "design.save()",
    ]
    with open(os.path.join(out, "arc1_t35_r06_isf.py"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(rows)} pins")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else HERE)
