#!/usr/bin/env python3
"""ARC-1 Compact R10 -- every-pin review tables, generated from board/r10_board_plan.json.

Writes cad/review/<ref>_<part>.csv for every multi-pin IC/connector (pin, name, electrical type, net, no-connect reason,
other members of the net) and cad/review/PIN_REVIEW_R10.md (summary + sign-off columns). Every pin must have either a
net or an explicit reason; the script exits 1 otherwise. The tables are for human review against the datasheets: they do
not replace that review.
Usage: pin_review.py <R10_WORK dir>
"""
import csv
import json
import os
import sys

R10 = os.path.abspath(sys.argv[1])
plan = json.load(open(os.path.join(R10, "board", "r10_board_plan.json")))
out = os.path.join(R10, "cad", "review")
os.makedirs(out, exist_ok=True)
for _f in os.listdir(out):                       # tables are regenerated from scratch (refs can renumber)
    if _f.endswith(".csv"):
        os.remove(os.path.join(out, _f))
SMALL = {"R0402", "R0603", "C0402", "C0603", "C0805", "C1210", "FB0603", "L4035", "F1812", "TP", "MH", "FID", "LED", "TVS_SMF",
         "SCHOTTKY", "SW_B3U", "PWR_FLAG"}
errors = []
rows_md = []
for c in sorted(plan["components"], key=lambda c: (c["sheet"], c["ref"])):
    if c["part"] in SMALL:
        continue
    fn = os.path.join(out, f"{c['ref']}_{c['part']}.csv")
    with open(fn, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["pin", "name", "etype", "net", "nc_reason", "net_members"])
        nets = nc = 0
        for p, d in sorted(c["pins"].items(), key=lambda kv: (len(kv[0]), kv[0])):
            members = ""
            if d["net"]:
                nets += 1
                m = [x for x in plan["nets"].get(d["net"], []) if not x.startswith(c["ref"] + ".")]
                members = " ".join(m[:12]) + (f" (+{len(m) - 12})" if len(m) > 12 else "")
            elif d["nc_reason"]:
                nc += 1
            else:
                errors.append(f"{c['ref']} pin {p} ({d['name']}) has neither a net nor a reason")
            w.writerow([p, d["name"], d["etype"], d["net"] or "", d["nc_reason"] or "", members if d["net"] not in ("GND",) else "(ground)"])
    rows_md.append(f"| {c['ref']} | {c['part']} | {c['value']} | {c['sheet']} | {len(c['pins'])} | {nets} | {nc} | "
                   f"{c['footprint_status']} | {'DNP' if c['dnp'] else ''} | [{os.path.basename(fn)}]({os.path.basename(fn)}) | |")
md = ["# R10 every-pin review (generated by cad/check/pin_review.py -- do not edit)", "",
      "One table per IC / connector. Every pin is either on a named net or carries a written no-connect reason. Review",
      "each table against the manufacturer document cited in the part's `Source` field (schematic symbol property) and",
      "initial the last column. Status of this file: generated, **not yet reviewed by a person**.", "",
      "| Ref | Part | Value | Sheet | Pins | On a net | NC with reason | Footprint | DNP | Table | Reviewed (initials/date) |",
      "|---|---|---|---|---|---|---|---|---|---|---|"] + rows_md
open(os.path.join(out, "PIN_REVIEW_R10.md"), "w").write("\n".join(md) + "\n")
print(f"{len(rows_md)} tables written to cad/review/")
for e in errors:
    print("ERROR", e)
print("PIN_REVIEW", "PASS" if not errors else "FAIL")
sys.exit(1 if errors else 0)
