#!/usr/bin/env python3
"""ARC-1 R10 -- 64 MiB F133-owned SPI NOR partition map (ARC1_MEMORY_R10 v0.1 section 4) -> R10_nor_partition.csv and
the C header used by the F133 bootloader (../firmware/f133_bootloader/include/r10_nor_layout.h). One source of truth.
Checks (exit 1 on any failure): 64 KiB block alignment, MiB alignment, contiguous and disjoint, exactly 64 MiB,
boot-ROM-read partitions below 16 MiB (3-byte addressing), and every measured image <= its partition."""
import csv, json, os, sys

H = os.path.dirname(os.path.abspath(__file__))
MiB = 1 << 20
DEVICE = 64 * MiB
# id, name, start MiB, end MiB, contents, written by, read by, protection, boot-ROM read?
P = [
    ("F1BT", "F133 boot / selector", 0x00, 0x01, "boot0 (eGON) at 0 + ARC-1 loader at 0x10000; manifest selector",
     "factory / recovery header only", "F133 boot ROM, then loader", "locked (individual block lock)", True),
    ("F1RC", "F133 rescue / diagnostics", 0x01, 0x03, "recovery image (USB device service, diagnostics); independent of A/B",
     "factory / recovery header only", "F133 loader", "locked", True),
    ("F1MA", "F133 firmware A", 0x03, 0x0B, "main F133 firmware", "updater (inactive slot only)", "F133 loader", "unlocked", False),
    ("F1MB", "F133 firmware B", 0x0B, 0x13, "main F133 firmware", "updater (inactive slot only)", "F133 loader", "unlocked", False),
    ("D2FA", "D213 firmware A", 0x13, 0x23, "bare-metal graphics firmware", "updater (inactive slot only)", "F133 -> D213 over USB", "unlocked", False),
    ("D2FB", "D213 firmware B", 0x23, 0x33, "bare-metal graphics firmware", "updater (inactive slot only)", "F133 -> D213 over USB", "unlocked", False),
    ("C12G", "ECP5-12F golden", 0x33, 0x35, "minimal link-safe 12F configuration", "factory", "F133 slave-SPI loader", "locked", False),
    ("C12A", "ECP5-12F application", 0x35, 0x37, "normal RGMII/compute 12F bitstream", "updater", "F133 slave-SPI loader", "unlocked", False),
    ("C45G", "ECP5-45F golden", 0x37, 0x3A, "known-good diagnostic / 2D-safe 45F configuration", "factory", "F133 -> D213 -> 45F slave SPI", "locked", False),
    ("C45A", "ECP5-45F application", 0x3A, 0x3D, "normal 3D rasterizer 45F bitstream", "updater", "F133 -> D213 -> 45F slave SPI", "unlocked", False),
    ("META", "Metadata / journals / reserve", 0x3D, 0x40, "two-copy manifests (2 x 64 KiB), settings, health counters, headroom",
     "F133 loader and updater", "F133", "unlocked", False),
]
# golden images are the same design class as the application images until a separate golden design exists
SIZE_OF = {"C12G": "C12A", "C45G": "C45A"}

def main():
    meas = json.load(open(os.path.join(H, "measured_images.json")))["images"]
    errs, rows, pos = [], [], 0
    for pid, name, s, e, what, wr, rd, prot, rom in P:
        base, end = s * MiB, e * MiB
        if base != pos: errs.append(f"{pid}: starts at {base:#x}, expected {pos:#x} (gap/overlap)")
        if end <= base: errs.append(f"{pid}: empty")
        if base % 0x10000 or end % 0x10000: errs.append(f"{pid}: not 64 KiB aligned")
        if rom and end > 16 * MiB: errs.append(f"{pid}: boot-ROM-read partition above 16 MiB (3-byte addressing)")
        m = meas.get(SIZE_OF.get(pid, pid))
        fit, mb = "no image yet", ""
        if m:
            mb = m["bytes_uncompressed"]
            fit = f"FITS {mb / (end - base):.0%} uncompressed ({m['label']})" if mb <= end - base else "DOES NOT FIT"
            if mb > end - base: errs.append(f"{pid}: measured image {mb} > partition {end - base}")
        rows.append({"id": pid, "partition": name, "offset": f"0x{base:08X}", "end_exclusive": f"0x{end:08X}",
                     "size_bytes": end - base, "size_mib": (end - base) // MiB, "contents": what, "written_by": wr,
                     "read_by": rd, "protection": prot, "boot_rom_reads": "yes" if rom else "no",
                     "measured_image_bytes": mb, "fit": fit,
                     "status": "PROPOSED (ARC1_MEMORY_R10 v0.1 s4 map, unchanged)"})
        pos = end
    if pos != DEVICE: errs.append(f"total {pos:#x} != 64 MiB")
    with open(os.path.join(H, "R10_nor_partition.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    hp = os.path.join(H, "..", "firmware", "f133_bootloader", "include", "r10_nor_layout.h")
    os.makedirs(os.path.dirname(hp), exist_ok=True)
    L = ["/* GENERATED by memory/gen_nor_partition.py from the ARC1_MEMORY_R10 v0.1 partition map -- do not edit. */",
         "#ifndef R10_NOR_LAYOUT_H", "#define R10_NOR_LAYOUT_H", "#include <stdint.h>",
         f"#define R10_NOR_SIZE 0x{DEVICE:08X}u",
         "enum r10_part { " + ", ".join(f"R10P_{p[0]} = {i}" for i, p in enumerate(P)) + f", R10P_COUNT = {len(P)} }};",
         "typedef struct r10_part_info { uint32_t tag, base, len; uint8_t locked; } r10_part_info;",
         "static const r10_part_info r10_parts[R10P_COUNT] = {"]
    for pid, name, s, e, *_r in P:
        tag = int.from_bytes(pid.encode(), "little")
        L.append(f"    {{ 0x{tag:08X}u, 0x{s * MiB:08X}u, 0x{(e - s) * MiB:08X}u, {1 if _r[3].startswith('locked') else 0} }},  /* {pid} {name} */")
    L += ["};", "#endif", ""]
    open(hp, "w").write("\n".join(L))
    for r in rows: print(f"{r['id']} {r['offset']}-{r['end_exclusive']} {r['size_mib']:>2} MiB  {r['fit']}")
    if errs:
        for e in errs: print("ERROR", e)
        return 1
    print(f"NOR_PARTITION_PASS {len(rows)} partitions, 64 MiB, 0 errors")
    return 0

if __name__ == "__main__":
    sys.exit(main())
