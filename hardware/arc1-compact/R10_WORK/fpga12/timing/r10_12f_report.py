#!/usr/bin/env python3
"""R10 12F fit/timing report from real tool logs. Utilisation is computed against the LFE5U-12F datasheet limits
(FPGA-DS-02012-3.4 Table 1.1: 12K LUTs, 32 sysMEM 18 kb blocks, 28 MULT18X18D, 2 PLLs) because nextpnr --12k uses the
25F die database and reports 25F totals. Gate (R10 6.3): <= 70 % LUT and EBR."""
import glob, json, os, re, sys
out, md, js = sys.argv[1], sys.argv[2], sys.argv[3]
LIM = {"LUT4": 12000, "DP16KD": 32, "MULT18X18D": 28, "EHXPLLL": 2}
ylog = open(os.path.join(out, "yosys.log")).read()
cells = {k: int(v) for k, v in re.findall(r"^\s+(LUT4|TRELLIS_FF|CCU2C|DP16KD|MULT18X18D|EHXPLLL|\$_DLATCH\w*)\s+(\d+)", ylog, re.M)}
res = {"synthesis_cells": cells, "runs": [], "limits_ds_12f": LIM}
def parse(path):
    t = open(path).read()
    fm = {m[0]: [float(m[1]), m[2]] for m in re.findall(r"Max frequency for clock\s+'\$glbnet\$([^']+)':\s+([\d.]+) MHz \((PASS|FAIL)", t)}
    comb = re.search(r"TRELLIS_COMB:\s+(\d+)/", t)
    return {"log": os.path.basename(path), "fmax": fm, "comb": int(comb.group(1)) if comb else None,
            "ok": bool(fm) and all(v[1] == "PASS" for v in fm.values())}
for p in sorted(glob.glob(os.path.join(out, "nextpnr_s*.log"))) + sorted(glob.glob(os.path.join(out, "seed_s*_*.log"))):
    res["runs"].append(parse(p))
comb = next((r["comb"] for r in res["runs"] if r["comb"]), None)
util = {"LUT4 (TRELLIS_COMB after P&R)": [comb, LIM["LUT4"]], "DP16KD": [cells.get("DP16KD", 0), LIM["DP16KD"]],
        "MULT18X18D": [cells.get("MULT18X18D", 0), LIM["MULT18X18D"]], "EHXPLLL": [2, LIM["EHXPLLL"]]}
res["utilisation"] = {k: {"used": u, "limit": l, "pct": round(100.0 * u / l, 1) if u is not None else None} for k, (u, l) in util.items()}
res["gate_70pct_lut_ebr"] = all(res["utilisation"][k]["pct"] is not None and res["utilisation"][k]["pct"] <= 70.0
                                for k in ("LUT4 (TRELLIS_COMB after P&R)", "DP16KD"))
res["all_runs_timing_pass"] = all(r["ok"] for r in res["runs"]) and bool(res["runs"])
json.dump(res, open(js, "w"), indent=1)
L = ["# R10 LFE5U-12F support FPGA: fit and timing (generated by timing/r10_12f_report.py)", "",
     "Tools: Yosys/nextpnr-ecp5/Project Trellis (versions: build/../R85C TOOL_VERSIONS). Device LFE5U-12F (`--12k`), "
     "package caBGA256 used as a PROXY for TQFP144 with the same PIO sites (timing/r10_12f_proxy256.lpf); TQFP144 "
     "pin-locked P&R: NOT_RUN (no TQFP144 in Trellis; needs Lattice Diamond/Radiant).", "",
     "| Resource | Used | 12F limit (DS) | % |", "|---|---|---|---|"]
L += [f"| {k} | {v['used']} | {v['limit']} | {v['pct']} |" for k, v in res["utilisation"].items()]
L += ["", f"R10 6.3 gate (<= 70 % LUT and EBR): **{'PASS' if res['gate_70pct_lut_ebr'] else 'FAIL'}**. "
      "PLLs: both used (no PLL headroom).", "", "| Run | sys_clk | eth_txclk | rgmii_rxc | result |", "|---|---|---|---|---|"]
for r in res["runs"]:
    f = r["fmax"]
    g = lambda k: next((f"{v[0]:.1f} ({v[1]})" for n, v in f.items() if n.startswith(k)), "-")
    L.append(f"| {r['log']} | {g('sys_clk')} | {g('eth_txclk')} | {g('rgmii_rxc')} | {'PASS' if r['ok'] else 'FAIL'} |")
L += ["", f"All runs meet timing: **{'YES' if res['all_runs_timing_pass'] else 'NO'}**. Requirements: sys_clk 80 MHz, "
      "eth_txclk / rgmii_rxc 125 MHz. Pad-level RGMII I/O timing is not analysed by nextpnr (see R8.5-C "
      "docs/RGMII_LINK_R85C.md budget; ECP5 GDDRX1 figures apply to all devices)."]
open(md, "w").write("\n".join(L) + "\n")
print(json.dumps({"gate": res["gate_70pct_lut_ebr"], "timing_all": res["all_runs_timing_pass"], "util": res["utilisation"]}))
sys.exit(0 if res["gate_70pct_lut_ebr"] and res["all_runs_timing_pass"] else 1)
