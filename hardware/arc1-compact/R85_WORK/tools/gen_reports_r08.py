#!/usr/bin/env python3
"""Generate sourcing/BOM_CANDIDATES.csv and docs/PIN_TABLE_R08.md from board/r08_board_plan.json."""
import collections, csv, json, os, re
R08 = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
plan = json.load(open(os.path.join(R08, "board", "r08_board_plan.json")))
comps = plan["components"]

# ---- BOM (grouped) ----
groups = collections.OrderedDict()
for c in sorted(comps, key=lambda c: (c["part"], c["value"], c["ref"])):
    if c["part"] in ("TP", "MH", "MH_NPTH", "FID"):
        continue
    k = (c["part"], c["value"], c["mpn"], c["footprint"], c["dnp"])
    groups.setdefault(k, []).append(c)
with open(os.path.join(R08, "sourcing", "BOM_CANDIDATES.csv"), "w", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["designators", "qty", "value", "mpn", "manufacturer", "lcsc", "footprint", "footprint_status", "dnp",
                "evidence", "slim4_reuse", "sourcing_status"])
    for (part, val, mpn, fp, dnp), cs in groups.items():
        c0 = cs[0]
        lcsc = c0["lcsc"]
        status = ("LCSC no. from SLIM4 R26 BOM (2026-10-07 snapshot) - re-check stock" if c0["slim4_reuse"] or (lcsc and part not in ("R0402", "C0402"))
                  else "TBD - R09 sourcing" if (not lcsc or "TBD" in (mpn or "")) else "candidate")
        w.writerow([" ".join(sorted((x["ref"] for x in cs), key=lambda r: (re.sub(r"\d", "", r), int(re.sub(r"\D", "", r) or 0)))),
                    len(cs), val, mpn or "generic (value/package)", c0["manufacturer"], lcsc, fp, c0["footprint_status"],
                    "DNP" if dnp else "", c0["evidence"], "yes" if c0["slim4_reuse"] else "", status])
# ---- pin table ----
L = ["# ARC-1 Compact R08 pin table (GENERATED from board/r08_board_plan.json; the KiCad schematic is generated from the same source)", ""]
def table(ref, title, only_connected=True, pins_filter=None):
    c = [x for x in comps if x["ref"] == ref][0]
    L.extend([f"## {ref} {c['value']} -- {title}", "", "| Pin | Name | Net | No-connect reason |", "|---|---|---|---|"])
    def key(p):
        m = re.match(r"^([A-Z]*)(\d+)$", p)
        return (m.group(1), int(m.group(2))) if m else (p, 0)
    for num in sorted(c["pins"], key=key):
        p = c["pins"][num]
        if pins_filter and not pins_filter(num, p):
            continue
        if only_connected and not p["net"]:
            continue
        L.append(f"| {num} | {p['name']} | {p['net'] or ''} | {p['nc_reason'] or ''} |")
    L.append("")
table("U15", "F133-B (all 129 pins incl. EPAD)", only_connected=False)
table("U18", "T35F400C3 (signal balls only; power/ground balls by rail in sources/efinix)",
      pins_filter=lambda n, p: p["net"] not in ("GND", "1V2_T35", "1V2_T35_PLL", "3V3_T35"))
table("J3", "MN820 CN1 mate (all 100 pins)", only_connected=False)
table("U16", "W25Q256JVFIQ boot NOR", only_connected=False)
table("U25", "APS6404L PSRAM", only_connected=False)
open(os.path.join(R08, "docs", "PIN_TABLE_R08.md"), "w").write("\n".join(L) + "\n")

# ---- interconnect matrix: device-to-device signal nets, domains, series parts, inactive state ----
byref = {c["ref"]: c for c in comps}
RAILS = {"3V3", "3V3_T35", "PSRAM_VDD", "3V3_MN", "SD_VDD", "1V8_LDOA", "VBUS_5V", "1V8_AN", "VDD_CORE", "1V8_DRAM",
         "1V2_T35", "1V2_T35_PLL", "GND", "VBUS_RAW", "3V3_REG"}
def domain(ref):
    c = byref[ref]
    if c["part"] == "MN820_RCPT": return "3V3_MN (module)"
    if c["part"] == "MICROSD": return "SD_VDD (card)"
    if c["part"] == "USB_C": return "USB cable"
    if c["part"] == "F133": return "3V3 (F133 VCC-IO/PD/PE/PG banks)"
    if c["part"] == "T35": return "3V3_T35 (T35 VCCIO, switched)"
    sup = sorted({p["net"] for p in c["pins"].values() if p["etype"] == "power_in" and p["net"] not in ("GND", None)})
    return "/".join(sup) or "-"
def is_dev(ref):
    return ref[0] in "UJX" and byref[ref]["part"] not in ("HDR_1x3", "HDR_2x5_127")
def series_peer(ref, net):
    c = byref[ref]
    o = c["pins"]["2" if c["pins"]["1"]["net"] == net else "1"]["net"]
    return o
M = ["# ARC-1 Compact R08 interconnect matrix (GENERATED by tools/gen_reports_r08.py from board/r08_board_plan.json)", "",
     "Every signal net that touches at least two devices, after following series resistors (<= 1 kOhm).",
     "'Inactive state' = the level set by board pulls while all drivers are high-Z/in reset (boot sampling, unpowered FPGA).",
     "Devices: U15 F133, U16 boot NOR, U17 MN820 MISO buffer, U18 T35, U19 T35 config flash, U21-U24 SPI0 isolation, "
     "U25 PSRAM, U26 PSRAM pull-down switch, J3 MN820, J7 microSD, J1 USB-C, U28/U29 amps.", "",
     "| Signal (net chain) | Endpoints (ref.pin name [domain]) | Pulls | Inactive / boot state |", "|---|---|---|---|"]
seen = set()
for net in sorted(plan["nets"]):
    if net in RAILS or net in seen:
        continue
    chain, todo = [], [net]
    while todo:
        n = todo.pop()
        if n in chain or n in RAILS:
            continue
        chain.append(n)
        for node in plan["nets"].get(n, []):
            r, pin = node.split(".")
            c = byref[r]
            if c["part"].startswith("R0") and not c["dnp"]:
                v = c["value"].replace("R", "")
                try:
                    ohm = float(v.replace("k", "")) * (1e3 if "k" in v else 1)
                except ValueError:
                    ohm = 1e9
                if ohm <= 1000:
                    todo.append(series_peer(r, n))
    seen.update(chain)
    ends, pulls = [], []
    for n in chain:
        for node in plan["nets"].get(n, []):
            r, pin = node.split(".")
            c = byref[r]
            if is_dev(r):
                ends.append(f"{r}.{pin} {c['pins'][pin]['name']} [{domain(r)}]")
            elif c["part"].startswith("R0") and not c["dnp"]:
                o = series_peer(r, n)
                if o in RAILS:
                    pulls.append(f"{c['value']} to {o}")
    if len({e.split('.')[0] for e in ends}) < 2:
        continue
    if any(p.endswith("to GND") for p in pulls) and not any(not p.endswith("to GND") for p in pulls):
        st = "LOW (pull-down)"
    elif pulls and all(not p.endswith("to GND") for p in pulls):
        st = "HIGH (pull-up to " + ", ".join(sorted({p.split(' to ')[1] for p in pulls})) + ")"
    elif pulls:
        st = "divider/mixed: " + "; ".join(pulls)
    else:
        st = "driven only (no pull)"
    M.append(f"| {' / '.join(chain)} | {'<br>'.join(ends)} | {', '.join(pulls) or '-'} | {st} |")
open(os.path.join(R08, "docs", "INTERCONNECT_MATRIX_R08.md"), "w").write("\n".join(M) + "\n")
print(f"interconnect rows {len(M) - 7}")
print(f"BOM lines {len(groups)}, components {len(comps)}")
