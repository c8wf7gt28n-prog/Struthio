#!/usr/bin/env python3
"""ARC-1 Compact R8.5 -- LFE5U-45F vs LFE5U-85F on caBGA381, ONLY from Lattice's published migration table
(sources/lattice/ecp5u_cabga381_migration.csv, rev 1.1). For every ball the R8.5 schematic connects, compare the
45F and 85F pin function, bank and dual function. A shared ball count is not compatibility (CO 3.3); this script
does not change the design and never selects the 85F. Output: docs/MIGRATION_45F_85F_R85.md; exit 0 always
(informative), result in the first line."""
import csv
import json
import os

R85 = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
rows = list(csv.reader(open(os.path.join(R85, "sources", "lattice", "ecp5u_cabga381_migration.csv"))))
hdr_i = [i for i, r in enumerate(rows) if r and r[0] == "Pin Number"][0]
dev = rows[hdr_i - 1]
cols = {name: i for i, name in enumerate(dev) if name.startswith("LFE5U")}
plan = json.load(open(os.path.join(R85, "board", "r85_board_plan.json")))
u18 = [c for c in plan["components"] if c["ref"] == "U18"][0]["pins"]
mig = {}
for r in rows[hdr_i + 1:]:
    if not r or not r[cols["LFE5U-45"]]:
        continue
    b45 = r[cols["LFE5U-45"]]
    mig[b45] = {"45": r[cols["LFE5U-45"]:cols["LFE5U-45"] + 7], "85": r[cols["LFE5U-85"]:cols["LFE5U-85"] + 7]}
diffs, same, missing = [], 0, []
for ball, p in sorted(u18.items()):
    if not p["net"]:
        continue
    m = mig.get(ball)
    if not m:
        missing.append(ball)
        continue
    a, b = m["45"], m["85"]
    if b[0] != ball:
        diffs.append((ball, p["net"], " ".join(a[1:4]), f"85F row lists ball {b[0]}"))
    elif (a[1].split("_")[0] if a[1].startswith("VCCIO") else a[1]) != (b[1].split("_")[0] if b[1].startswith("VCCIO") else b[1]) \
            or a[2] != b[2] or a[3] != b[3]:
        kind = "function name only (same bank/dual)" if a[2] == b[2] and a[3] == b[3] else "bank or dual-function differs"
        diffs.append((ball, p["net"], f"{a[1]} bank {a[2]} {a[3]}", f"{b[1]} bank {b[2]} {b[3]} [{kind}]"))
    else:
        same += 1
serious = [d for d in diffs if "differs" in d[3] or "lists ball" in d[3]]
L = [f"RESULT: {len(serious)} connected balls change bank/dual function on the 85F; {len(diffs) - len(serious)} change pad name only; "
     f"{same} identical; {len(missing)} not in the migration table",
     "", "# LFE5U-45F vs LFE5U-85F (caBGA381) for the R8.5 netlist (GENERATED by tools/check_migration_r85.py)", "",
     "Source: Lattice 'ECP5U caBGA381 Pin Migration' CSV rev 1.1 (sources/lattice/sources.json id MIG381). Only connected "
     "balls of U18 are compared. **The 85F is not selected.** Pad-name changes (e.g. PL23A -> PL35A) matter only to the "
     "LPF/bitstream, which must be rebuilt for the 85F device anyway (different IDCODE 0x41113043, the loader rejects "
     "cross-device images, FIT X01). Power, configuration and the bank of every signal must stay identical for a "
     "board-compatible option. Supply currents, timing and the bitstream size (85F about 2x) differ and are NOT covered "
     "by this table.", "",
     "| Ball | Net | 45F | 85F |", "|---|---|---|---|"]
L += [f"| {d[0]} | {d[1]} | {d[2]} | {d[3]} |" for d in diffs]
open(os.path.join(R85, "docs", "MIGRATION_45F_85F_R85.md"), "w").write("\n".join(L) + "\n")
print(L[0])
