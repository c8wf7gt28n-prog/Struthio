#!/usr/bin/env python3
"""ARC-1 Compact R8.5 -- failure-injection table (CO 7.1 + 6.2) generated from real test output:
firmware/build/test_r85 (FIT lines, behavioural board model) and fpga_ecp5/build/sim_ecp5_top.log (RTL).
Exit 1 if any CO 7.1 case lacks a passing row. Output: docs/FAILURE_INJECTION_R85.md"""
import os
import re
import subprocess
import sys

R85 = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
fw = subprocess.run([os.path.join(R85, "firmware", "build", "test_r85")], stdout=subprocess.PIPE).stdout.decode()
fits = [l.split(" | ") for l in fw.splitlines() if l.startswith("FIT ") and not l.startswith("FIT_SUMMARY")]
rtl = open(os.path.join(R85, "fpga_ecp5", "build", "sim_ecp5_top.log")).read()
rtl_tests = dict(re.findall(r"^TEST (\S+) done errors=(\d+)", rtl, re.M))
rtl_pass = "TOP_ECP5_TB_PASS" in rtl
CO = [  # CO 7.1 case -> rows that cover it (firmware FIT ids and/or RTL tests)
    ("blank NOR", ["F01"], []),
    ("wrong NOR BOOT straps", ["F02"], []),
    ("FPGA at power-off", ["F03a", "F03b", "F03c"], ["P0_unpowered_start"]),
    ("ECP5 configuration CRC fault", ["F04a", "F04b", "F04c"], []),
    ("PROGRAMN held active", ["F05"], []),
    ("QSPI CE# stuck active", ["F06"], ["F06_ce_stuck"]),
    ("PSRAM missing", ["F07a", "F07b"], ["P0_unpowered_start", "P4_unannounced_loss"]),
    ("FPGA-CPU protocol version mismatch", ["F08a", "F08b"], ["ajob_crosssim"]),
    ("F133 software crash mid-configuration", ["F09a", "F09b"], ["fpga_reset"]),
    ("bad microSD", ["F10a", "F10b", "F10c"], []),
    ("ECP5 rail sequencing fault", ["F11", "F03a"], []),
]
by = {f[0].split()[1]: f for f in fits}
L = ["# R8.5 failure-injection table (GENERATED by tools/gen_fit_doc_r85.py from test output)", "",
     "Firmware rows run the real F133 loader/service code (firmware/src) against a behavioural board model "
     "(firmware/tests/ecp5_mock.c). RTL rows are tb_ecp5_top (Icarus) on the real ECP5 RTL with the APS6404L model. "
     "No hardware was used. Every case returns to a defined state: P1 launcher with the FPGA powered down and isolated, "
     "or a documented degraded mode. NOR boot, BT820 graphics and USB never depend on the FPGA: the service never "
     "touches SPI1, and the NOR CS line is owned by the F133.", "",
     "## Change order 7.1 coverage", "", "| CO case | Covered by | Result |", "|---|---|---|"]
missing = []
for case, fids, rids in CO:
    ok = all(f in by and by[f][-1].strip() == "PASS" for f in fids) and all(rtl_tests.get(r) == "0" for r in rids) and (rtl_pass or not rids)
    if not ok:
        missing.append(case)
    res = "PASS" if ok else "FAIL/MISSING"
    if fids in (["F01"], ["F02"]):
        res = ("BY REFERENCE: R08 boot-trace/recovery dossier (BROM -> FEL), bench item" if fids == ["F01"]
               else "BY REFERENCE: board/test_check_board_r85.py strap negative tests (static)")
    L.append(f"| {case} | {', '.join(fids + ['RTL ' + r for r in rids])} | {res} |")
L += ["", "## All firmware cases (FIT lines)", "", "| ID | Case | Expected outcome | Observed | Result |", "|---|---|---|---|---|"]
for f in fits:
    fid, name = f[0].split()[1], f[0].split()[2]
    L.append(f"| {fid} | {name} | {f[1]} | {f[2].replace('|', '/')} | {f[3].strip()} |")
L += ["", "## RTL system testbench sections (tb_ecp5_top)", "", "| Test | Errors |", "|---|---|"]
for k, v in rtl_tests.items():
    L.append(f"| {k} | {v} |")
info = [l for l in rtl.splitlines() if l.startswith("INFO F06") or l.startswith("INFO ajob abort") or l.startswith("INFO P4")]
L += ["", "RTL observations:", ""] + [f"* `{l}`" for l in info] + ["", f"tb_ecp5_top verdict: {'TOP_ECP5_TB_PASS' if rtl_pass else 'FAIL'}", ""]
open(os.path.join(R85, "docs", "FAILURE_INJECTION_R85.md"), "w").write("\n".join(L) + "\n")
print(f"FIT rows {len(fits)}, RTL tests {len(rtl_tests)}, CO cases {len(CO)}, missing {missing}")
sys.exit(1 if missing else 0)
