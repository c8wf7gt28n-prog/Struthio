#!/usr/bin/env python3
"""Generate include/board_pins_r85.h (F133 GPIO -> net) from board/r85_board_plan.json.
The header is checked back against the KiCad netlist by cad/check/crosscheck_r85.py."""
import json, os, re, sys
R85 = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
plan = json.load(open(os.path.join(R85, "board", "r85_board_plan.json")))
u = [c for c in plan["components"] if c["ref"] == "U15"][0]
lines = ["/* GENERATED by firmware/tools/gen_board_pins.py from board/r85_board_plan.json -- do not edit.",
         " * F133 GPIO assignment of the R8.5 schematic (U15). ARC1_PIN(port, index). */",
         "#ifndef BOARD_PINS_R85_H", "#define BOARD_PINS_R85_H",
         "#define ARC1_PIN(port, idx) ((unsigned)(((port) - 'A') * 32 + (idx)))"]
rows = []
for num, p in u["pins"].items():
    m = re.match(r"^P([A-G])(\d+)$", p["name"])
    if m and p["net"]:
        rows.append((p["net"], m.group(1), int(m.group(2)), num))
for net, port, idx, num in sorted(rows, key=lambda r: (r[1], r[2])):
    lines.append(f"#define PIN_{net:<16} ARC1_PIN('{port}', {idx:2d})   /* pin {num} */")
lines += ["#endif", ""]
open(os.path.join(R85, "firmware", "include", "board_pins_r85.h"), "w").write("\n".join(lines))
print(f"board_pins_r85.h: {len(rows)} pins")
