#!/bin/sh
# ARC-1 Compact R8.5 -- record the exact open-toolchain versions and binary hashes used for a build.
# Usage: record_tools.sh OUTFILE
set -e
out="$1"
{
  echo "# ARC-1 R8.5 ECP5 build tool pin (generated by build_scripts/record_tools.sh)"
  echo "host_os: $(. /etc/os-release && echo "$PRETTY_NAME")"
  for p in yosys nextpnr-ecp5 fpga-trellis openfpgaloader iverilog verilator kicad; do
    v=$(dpkg-query -W -f='${Version}' "$p" 2>/dev/null || echo NOT_INSTALLED)
    echo "dpkg $p $v"
  done
  echo "yosys_version: $(yosys -V)"
  echo "nextpnr_version: $(nextpnr-ecp5 --version 2>&1 | head -1)"
  echo "trellis_db: $(ls -d /usr/share/trellis/database/ECP5/LFE5U-45F 2>/dev/null)"
  echo "trellis_db_iodb_sha256: $(sha256sum /usr/share/trellis/database/ECP5/LFE5U-45F/iodb.json | cut -d' ' -f1)"
  for b in yosys nextpnr-ecp5 ecppack ecppll openFPGALoader iverilog vvp verilator; do
    p=$(command -v "$b" || true)
    if [ -n "$p" ]; then echo "sha256 $b $(sha256sum "$(readlink -f "$p")" | cut -d' ' -f1)"; fi
  done
} > "$out"
cat "$out"
