#!/usr/bin/env python3
"""ARC-1 Compact R8.5 -- build report from real tool outputs (yosys.log, nextpnr report/log, .bit).
Fails (exit 1) if timing is not met, a latch was inferred, or the bit file is missing.
Usage: build_report.py BUILD_DIR OUT_JSON OUT_MD"""
import hashlib
import json
import os
import re
import sys

b, oj, om = sys.argv[1:4]
ylog = open(os.path.join(b, "yosys.log")).read()
stat = ylog[ylog.rindex("=== arc1_ecp5_top ==="):]
cells = {m.group(1): int(m.group(2)) for m in re.finditer(r"^\s+(\S+)\s+(\d+)$", stat.split("CHECK pass")[0], re.M)}
latches = sum(v for k, v in cells.items() if "LATCH" in k.upper())
rep = json.load(open(os.path.join(b, "nextpnr_report.json")))
log = open(os.path.join(b, "nextpnr.log")).read()
bit = os.path.join(b, "arc1_ecp5.bit")
data = open(bit, "rb").read()
fmax = {k.replace("$glbnet$", ""): {"achieved_MHz": round(v["achieved"], 2), "constraint_MHz": v["constraint"],
                                    "pass": v["achieved"] >= v["constraint"]} for k, v in rep["fmax"].items()}
crit = []
for cp in rep.get("critical_paths", []):
    delay = sum(x.get("delay", 0) for x in cp["path"])
    crit.append({"from": str(cp["from"]).replace("$glbnet$", ""), "to": str(cp["to"]).replace("$glbnet$", ""),
                 "delay_ns": round(delay, 3),
                 "endpoint": cp["path"][-1].get("to", {}).get("cell") if cp["path"] else None})
warn = sorted(set(l.strip() for l in log.splitlines() if l.startswith("Warning")))
out = {
    "target": {"device": "LFE5U-45F", "package": "CABGA381", "speed": 6, "top": "arc1_ecp5_top",
               "lpf": "fpga_ecp5/constraints/arc1_ecp5_r85.lpf (generated from board/r85_board_plan.json)"},
    "synthesis_cells": cells, "latches": latches,
    "utilization": {k: v for k, v in rep["utilization"].items() if v["used"]},
    "fmax": fmax, "critical_paths": crit, "nextpnr_warnings": warn,
    "multiplier_mapping": "8 x MULT18X18D, all in arc1_transform_ecp5 S1: two 32x32 products per issue cycle split into "
                          "4 signed 17x17 partial products each (hi17/lo17); no sharing between products, no ALU54B "
                          "cascades (not used; open-tool DSP inference limits, Trellis README). 64 of 72 MULT18X18D free.",
    "bitstream": {"file": "arc1_ecp5.bit", "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                  "ecppack": "--compress"},
    "evidence": "OPEN_TOOLCHAIN_ROUTED (Yosys/nextpnr-ecp5/Trellis); not programmed into silicon",
}
ok = all(v["pass"] for v in fmax.values()) and latches == 0 and len(data) > 0
out["result"] = "PASS" if ok else "FAIL"
json.dump(out, open(oj, "w"), indent=1)
md = ["# ECP5 open-toolchain build report (generated by build_scripts/build_report.py)", "",
      f"Target LFE5U-45F-6BG381C, top `arc1_ecp5_top`; result **{out['result']}** (routed bitstream, not on silicon).", "",
      "| Clock | Constraint MHz | Achieved MHz | Pass |", "|---|---|---|---|"]
md += [f"| {k} | {v['constraint_MHz']} | {v['achieved_MHz']} | {v['pass']} |" for k, v in fmax.items()]
md += ["", "| Resource | Used | Available |", "|---|---|---|"]
md += [f"| {k} | {v['used']} | {v['available']} |" for k, v in out["utilization"].items()]
md += ["", f"Synthesis: LUT4 {cells.get('LUT4')}, TRELLIS_FF {cells.get('TRELLIS_FF')}, CCU2C {cells.get('CCU2C')}, "
           f"DP16KD {cells.get('DP16KD')}, MULT18X18D {cells.get('MULT18X18D')}, latches {latches}.", "",
       f"Multipliers: {out['multiplier_mapping']}", "",
       f"Bitstream: {len(data)} bytes, sha256 `{out['bitstream']['sha256']}`.", "",
       "nextpnr warnings: " + ("none" if not warn else "; ".join(warn)), ""]
open(om, "w").write("\n".join(md))
print(json.dumps({"result": out["result"], "fmax": fmax, "bit_sha256": out["bitstream"]["sha256"]}))
sys.exit(0 if ok else 1)
