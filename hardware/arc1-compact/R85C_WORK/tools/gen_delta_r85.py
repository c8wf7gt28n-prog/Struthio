#!/usr/bin/env python3
"""ARC-1 Compact R8.5 -- T35 -> ECP5 delta table (CO Appendix A step 5: old net/reference -> new net/reference ->
verification evidence), generated by diffing the frozen R08 board plan against the R8.5 board plan, plus the
non-schematic deltas (RTL, constraints, firmware, tools). Output: docs/T35_TO_ECP5_DELTA_R85.md + .csv"""
import csv
import json
import os

R85 = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OLD = json.load(open(os.path.join(R85, "..", "R08_WORK", "board", "r08_board_plan.json")))
NEW = json.load(open(os.path.join(R85, "board", "r85_board_plan.json")))
oc = {c["ref"]: c for c in OLD["components"]}
nc = {c["ref"]: c for c in NEW["components"]}
rows = []


def ev_for(net_or_ref):
    s = net_or_ref
    if any(k in s for k in ("PROGRAMN", "INITN", "DONE", "CFG", "TCK", "TMS", "TDI", "TDO", "HOLDN")):
        return "board rule ecp5_sysconfig; ERC; FIT F05/X02/X03; crosscheck A"
    if any(k in s for k in ("1V1", "2V5", "3V3_FPGA", "PWR_EN", "VCC_PG")):
        return "board rules fpga_power_sequencing/fpga_vcc_voltage/ecp5_decoupling; margins fpga_rails; FIT F03a/F11"
    if "PSRAM" in s:
        return "board rule psram_power_architecture; tb_ecp5_top P0-P4/F06; margins psram"
    if any(k in s for k in ("SCK", "MOSI", "MISO", "SS_N", "BUS_EN", "IRQ")):
        return "board rule spi0_fpga_isolated; crosscheck C (LPF/RTL/routed); tb_ecp5_top; FIT X06-X10"
    if "OSC" in s:
        return "crosscheck C (P3 = LLC_GPLL0T_IN); routed build FREQUENCY constraint"
    return "ERC 0; crosscheck A/B"


# F133-anchored net mapping
fo = {p["name"]: p["net"] for p in oc["U15"]["pins"].values()}
fn = {p["name"]: p["net"] for p in nc["U15"]["pins"].values()}
for pin in sorted(set(fo) | set(fn)):
    if fo.get(pin) != fn.get(pin):
        rows.append(("F133 pin", f"U15 {pin}: {fo.get(pin) or '(unused)'}", f"U15 {pin}: {fn.get(pin) or '(unused)'}",
                     "re-assessed for ECP5 sysCONFIG/control (CO App. A row 'F133 control and boot')", ev_for(str(fn.get(pin)))))
# rail renames
for old, new, why in (("1V2_T35", "1V1_FPGA", "ECP5 VCC 1.1 V (DS Table 3.2); U9 FB 100k/100k -> 82.5k/100k"),
                      ("1V2_T35_PLL", "(removed)", "no ECP5 PLL supply ball; VCCAUX 2.5 V instead"),
                      ("(none)", "2V5_FPGA_AUX", "new VCCAUX rail: U30 TLV75525P + FB2 ferrite"),
                      ("3V3_T35", "3V3_FPGA", "all VCCIO banks 0/1/2/3/6/7/8; U10 ON = FPGA_PWR_EN (was 1V2 PG)"),
                      ("T35_PWR_EN", "FPGA_PWR_EN (+FPGA_PWR_EN_F via 1k)", "single shared enable; J11 service override"),
                      ("T35_1V2_PG", "FPGA_VCC_PG", "no longer sequences VCCIO; read by F133 PD1 for rail diagnosis"),
                      ("CDONE_DLY / CDONE_RC", "DONE_DLY / DONE_RC", "same RC+Schmitt delay, from ECP5 DONE"),
                      ("T35_CDONE", "FPGA_DONE", "open-drain DONE, 4.7k to VCCIO8"),
                      ("T35_CRESET_N / _F", "FPGA_PROGRAMN / _F", "PROGRAMN, 4.7k pull-up (T35: 4.7k pull-down hold), 470R series"),
                      ("(none)", "FPGA_INITN", "new: INITN to F133 PD0"),
                      ("CFG_SS_N/CFG_CCK/CFG_CDI0/CFG_CDI1/CFG_IO2/CFG_IO3", "(removed)", "U19 config flash removed: F133 streams over SSPI"),
                      ("T35_SCK / T35_MOSI / T35_MISO / T35_SS_N", "FPGA_SCK(+_B) / FPGA_MOSI / FPGA_MISO / FPGA_SS_N",
                       "now also the sysCONFIG SSPI pins (CCLK U3 + D7 R1, D0 W2, D1 V2, SN T2)"),
                      ("T35_IRQ_N", "FPGA_IRQ_N", "bank 0 E6 (hot-socket tolerant), 4.7k pull-up"),
                      ("T35_OSC_25M", "FPGA_OSC_25M", "P3 LLC_GPLL0T_IN"),
                      ("PSRAM_SCLK_T", "PSRAM_SCLK_F", "bank 6 L2"),
                      ("PD_CE/PD_SCLK/PD_SIO0..3", "(removed)", "U26 + 6x1.5k removed: ECP5 pulls DOWN during configuration"),
                      ("T35_TEST_N / T35_CSI", "(removed)", "no ECP5 equivalent"),
                      ("T35_TCK/TMS/TDI/TDO", "FPGA_TCK/TMS/TDI/TDO", "JTAG on VCCIO8; J5 ARM-10 layout, pin 10 = PROGRAMN"),
                      ("T35_LED0 / T35_DBG_TX / T35_DBG_RX", "FPGA_LED0 / FPGA_DBG_TX / FPGA_DBG_RX(_J)", "bank 0 A7/A8/B8; 1k series on RX")):
    rows.append(("net/rail", old, new, why, ev_for(new)))
# component diff: ICs/connectors by reference; passives (auto-numbered) as a multiset of (part, value, nets) after
# applying the R08 -> R8.5 net renames, so a renumbered but unchanged resistor is not reported
REN = {"1V2_T35": "1V1_FPGA", "1V2_T35_REG": "1V1_FPGA_REG", "3V3_T35": "3V3_FPGA", "T35_PWR_EN": "FPGA_PWR_EN",
       "T35_1V2_PG": "FPGA_VCC_PG", "SW_1V2": "SW_1V1", "FB_1V2": "FB_1V1", "SW_T35_CT": "SW_FPGA_CT",
       "CDONE_DLY": "DONE_DLY", "CDONE_RC": "DONE_RC", "CDONE_DIS": "DONE_DIS", "T35_CDONE": "FPGA_DONE",
       "T35_CRESET_N": "FPGA_PROGRAMN", "T35_CRESET_N_F": "FPGA_PROGRAMN_F", "PSRAM_SCLK_T": "PSRAM_SCLK_F",
       "T35_OSC_25M": "FPGA_OSC_25M", "T35_OSC_25M_X": "FPGA_OSC_25M_X", "T35_LED0": "FPGA_LED0", "T35_LED0_R": "FPGA_LED0_R"}
def rn(n):
    if n is None:
        return None
    return REN.get(n, "FPGA_" + n[4:] if n.startswith("T35_") else n)
PASSIVE = ("R0", "C0", "FB", "TP", "PWR")
old_p, new_p = {}, {}
for c in OLD["components"]:
    if c["part"].startswith(PASSIVE):
        k = (c["part"], c["value"], tuple(sorted(str(rn(p["net"])) for p in c["pins"].values())))
        old_p.setdefault(k, []).append(c["ref"])
for c in NEW["components"]:
    if c["part"].startswith(PASSIVE):
        k = (c["part"], c["value"], tuple(sorted(str(p["net"]) for p in c["pins"].values())))
        new_p.setdefault(k, []).append(c["ref"])
for k in sorted(set(old_p) | set(new_p), key=str):
    no, nn = len(old_p.get(k, [])), len(new_p.get(k, []))
    if no > nn:
        rows.append(("passive removed", f"{no - nn} x {k[0]} {k[1]} on {'/'.join(k[2])}", "-", "", ev_for("/".join(k[2]))))
    elif nn > no:
        rows.append(("passive added", "-", f"{nn - no} x {k[0]} {k[1]} on {'/'.join(k[2])} ({' '.join(new_p[k][:6])})", "",
                     ev_for("/".join(k[2]))))
for ref in sorted(set(oc) | set(nc), key=lambda r: (r.rstrip("0123456789"), int("0" + "".join(ch for ch in r if ch.isdigit())))):
    a, b = oc.get(ref), nc.get(ref)
    if (a and a["part"].startswith(PASSIVE)) or (b and b["part"].startswith(PASSIVE)):
        continue
    if a and not b:
        rows.append(("component removed", f"{ref} {a['part']} {a['value']}", "-", a.get("note", "")[:90], "ERC 0; board rules"))
    elif b and not a:
        rows.append(("component added", "-", f"{ref} {b['part']} {b['value']}", b.get("note", "")[:90], ev_for(" ".join(str(p['net']) for p in b['pins'].values()))))
    elif (a["part"], a["value"]) != (b["part"], b["value"]) or {k: rn(v["net"]) for k, v in a["pins"].items()} != {k: v["net"] for k, v in b["pins"].items()}:
        rows.append(("component changed", f"{ref} {a['part']} {a['value']}", f"{ref} {b['part']} {b['value']}",
                     (b.get("note") or "nets re-wired")[:90], ev_for(" ".join(str(p['net']) for p in b['pins'].values()))))
# non-schematic
for old, new, ev in (
        ("fpga/rtl/arc1_t35_top_r08.sv (Efinity pad split)", "fpga_ecp5/rtl/arc1_ecp5_top.sv (real tri-states, ecppll PLL)", "tb_ecp5_top PASS; lint; routed build"),
        ("R06 mbx_loopback.sv", "fpga_ecp5/rtl/accel_engine.sv (AJOB v1 + legacy loopback)", "tb_ecp5_top golden + 11 AJOB cases + abort; C cross-sim"),
        ("R05 arc1_transform.sv (single cycle, 21 MHz on ECP5)", "fpga_ecp5/rtl/arc1_transform_ecp5.sv (8 x MULT18X18D pipeline)", "unchanged R05 testbench 1165 oracle vectors PASS"),
        ("fpga/rtl/mbx_regs_r08.sv (AMBX v2)", "fpga_ecp5/rtl/mbx_regs_r85.sv (AMBX v3: perf, ABORT, CAPS bit3)", "tb_ecp5_top ident/perf checks"),
        ("fpga/efinity/* (ISF/SDC/XML generator; NATIVE_EDA_NOT_RUN)", "fpga_ecp5/constraints/arc1_ecp5_r85.lpf generated by tools/gen_pin_matrix_r85.py", "crosscheck C; BUILD_REPORT (Yosys/nextpnr/ecppack)"),
        ("(none)", "fpga_ecp5/Makefile + build_scripts (pinned tools, report, repro)", "REPRO_IDENTICAL; TOOL_VERSIONS.txt"),
        ("firmware: no T35 loader (T35 self-configured from U19)", "firmware/src/ecp5_cfg.c, fpga_link.c, accel_job.c, accel_service.c", "799 host checks, 33 FIT cases, 10 mutants killed"),
        ("f133_diag S4 CRESET/CDONE", "f133_diag S4 ecp5_probe (READ_ID) / S5 AMBX v3", "BUILD_ONLY, eGON checked, fits SRAM A1"),
        ("board/check_board_r08.py", "board/check_board_r85.py (+6 ECP5 rules)", "16/16 rules, 29 negative tests"),
        ("cad/check/crosscheck_r08.py (Efinity table)", "cad/check/crosscheck_r85.py (LPF/pinout/RTL/routed)", "CROSSCHECK PASS")):
    rows.append(("source", old, new, "", ev))

with open(os.path.join(R85, "docs", "T35_TO_ECP5_DELTA_R85.csv"), "w", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["kind", "R08 (old ref/net)", "R8.5 (new ref/net)", "reason", "verification evidence"])
    w.writerows(rows)
L = ["# T35 → ECP5 delta table (GENERATED by tools/gen_delta_r85.py from R08_WORK/board/r08_board_plan.json vs board/r85_board_plan.json)", "",
     f"{len(rows)} rows. The R08 sources are untouched (frozen); every row below is a difference between the two generated board plans "
     "or a source-level replacement. Evidence names refer to steps of tools/run_r85_checks.py.", "",
     "| Kind | R08 (old) | R8.5 (new) | Reason | Verification evidence |", "|---|---|---|---|---|"]
for r in rows:
    L.append("| " + " | ".join(str(x).replace("|", "/") for x in r) + " |")
open(os.path.join(R85, "docs", "T35_TO_ECP5_DELTA_R85.md"), "w").write("\n".join(L) + "\n")
print(f"delta rows {len(rows)}")
